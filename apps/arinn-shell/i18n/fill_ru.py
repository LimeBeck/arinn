def main(path: Path) -> int:
    tree = ET.parse(path)
    missing = []
    for ctx in tree.getroot().findall("context"):
        name = ctx.findtext("name")
        for message in ctx.findall("message"):
            source = message.findtext("source")
            text = CONTEXT.get((name, source), RU.get(source))
            translation = message.find("translation")
            if text is None:
                missing.append(f"{name}: {source!r}")
                continue
            translation.attrib.pop("type", None)
            if message.get("numerus") == "yes":
                for child in list(translation):
                    translation.remove(child)
                translation.text = None
                for _ in range(3):  # Russian: one, few, many
                    ET.SubElement(translation, "numerusform").text = text
            else:
                translation.text = text
    ET.indent(tree, space="    ")
    tree.write(path, encoding="utf-8", xml_declaration=True)
    for item in missing:
        print("untranslated:", item)
    return 1 if missing else 0


