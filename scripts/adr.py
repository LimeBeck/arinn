"""ADR helpers (ADR-0028, ADR-0034).

    python scripts/adr.py next                 print the next free ADR number
    python scripts/adr.py new NUMBER "Title"   create docs/adr/NUMBER-slug.md from the template
    python scripts/adr.py register             regenerate the register table in docs/adr/README.md
    python scripts/adr.py check                exit 1 if numbers collide or the register is stale

The ADR number of a new decision is reserved in its issue before work starts,
so parallel branches never pick the same number (see CONTRIBUTING.md).
"""

import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADR_DIR = ROOT / "docs/adr"
REGISTER = ADR_DIR / "README.md"
START = "<!-- register:start (generated by scripts/adr.py register; do not edit) -->"
END = "<!-- register:end -->"
FILE = re.compile(r"^(\d{4})-[a-z0-9-]+\.md$")


def adr_files() -> list[Path]:
    return sorted(p for p in ADR_DIR.iterdir() if FILE.match(p.name))


def field(text: str, name: str) -> str:
    match = re.search(rf"^- \*\*{re.escape(name)}:\*\* (.*)$", text, re.MULTILINE)
    return match.group(1).strip() if match else ""


def entry(path: Path) -> tuple[str, str, str, str]:
    text = path.read_text(encoding="utf-8")
    number = path.name[:4]
    title = re.match(r"^# ADR-\d{4}: (.*)$", text.splitlines()[0])
    status = field(text, "Status").split()[0] if field(text, "Status") else "?"
    successors = sorted(set(re.findall(r"ADR-(\d{4})", field(text, "Amended by / Superseded by"))))
    return number, title.group(1) if title else "?", status, ", ".join(successors) or "—"


def register_table() -> str:
    lines = [
        "| ADR | Title | Status | Amended / superseded by |",
        "| --- | --- | --- | --- |",
    ]
    for path in adr_files():
        number, title, status, successors = entry(path)
        lines.append(f"| [{number}]({path.name}) | {title} | {status} | {successors} |")
    return "\n".join(lines)


def render_register(readme: str) -> str:
    if START not in readme or END not in readme:
        raise SystemExit(f"{REGISTER.relative_to(ROOT)} lacks the register markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{register_table()}\n{END}{tail}"


def duplicates() -> list[str]:
    seen: dict[str, list[str]] = {}
    for path in adr_files():
        seen.setdefault(path.name[:4], []).append(path.name)
    return [f"ADR number {n} is used by {', '.join(names)}" for n, names in seen.items() if len(names) > 1]


def next_number() -> str:
    numbers = [int(p.name[:4]) for p in adr_files()]
    return f"{max(numbers, default=0) + 1:04d}"


def new(number: str, title: str) -> Path:
    if not re.fullmatch(r"\d{4}", number):
        raise SystemExit("NUMBER must have four digits, e.g. 0035")
    if any(p.name.startswith(number + "-") for p in adr_files()):
        raise SystemExit(f"ADR-{number} already exists")
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60].rstrip("-")
    path = ADR_DIR / f"{number}-{slug}.md"
    text = (ADR_DIR / "template.md").read_text(encoding="utf-8")
    text = text.replace("# ADR-NNNN: Short decision title", f"# ADR-{number}: {title}", 1)
    text = text.replace("YYYY-MM-DD", date.today().isoformat(), 1)
    path.write_text(text, encoding="utf-8")
    REGISTER.write_text(render_register(REGISTER.read_text(encoding="utf-8")), encoding="utf-8")
    return path


def check() -> list[str]:
    problems = duplicates()
    readme = REGISTER.read_text(encoding="utf-8")
    if START not in readme or END not in readme:
        problems.append("docs/adr/README.md lacks the register markers")
    elif render_register(readme) != readme:
        problems.append("docs/adr/README.md register is stale: run python scripts/adr.py register")
    return problems


def main(argv: list[str]) -> int:
    if argv == ["next"]:
        print(next_number())
        return 0
    if len(argv) == 3 and argv[0] == "new":
        print(new(argv[1], argv[2]).relative_to(ROOT))
        return 0
    if argv == ["register"]:
        REGISTER.write_text(render_register(REGISTER.read_text(encoding="utf-8")), encoding="utf-8")
        return 0
    if argv == ["check"]:
        problems = check()
        for problem in problems:
            print(f"error: {problem}")
        return 1 if problems else 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
